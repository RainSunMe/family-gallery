export const messages: Record<Locale, Dict> = { en, zh };

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  let text = messages[locale][key] ?? messages.en[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

// The server's DEFAULT_LANGUAGE is the fallback for visitors who never picked a
// language. The login page has no switcher; only the settings dialog stores a
// preference, so an explicit choice always wins over the configured default.
let serverDefault: Locale | null = null;
const serverDefaultListeners = new Set<(next: Locale) => void>();

function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const fromQuery = new URLSearchParams(window.location.search).get('lang');
  if (fromQuery === 'zh' || fromQuery === 'en') return fromQuery;
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'zh' || stored === 'en') return stored;
  if (serverDefault) return serverDefault;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function applyDefaultLocale(value: unknown) {
  const next: Locale | null = value === 'zh' || value === 'en' ? value : null;
  if (!next || next === serverDefault) return;
  serverDefault = next;
  if (typeof window === 'undefined') return;
  const fromQuery = new URLSearchParams(window.location.search).get('lang');
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (fromQuery === 'zh' || fromQuery === 'en' || stored === 'zh' || stored === 'en') return;
  serverDefaultListeners.forEach(listener => listener(next));
}

type I18nValue = {
  locale: Locale;
  setLocale: (next: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue>({
  locale: 'en',
  setLocale: () => {},
  t: (key, vars) => translate('en', key, vars),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectLocale());
  useEffect(() => {
    const listener = (next: Locale) => setLocaleState(next);
    serverDefaultListeners.add(listener);
    return () => { serverDefaultListeners.delete(listener); };
  }, []);
  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
  }, []);
  useEffect(() => { document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'; }, [locale]);
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, vars) => translate(locale, key, vars),
  }), [locale, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }

export function useT() { return useContext(I18nContext).t; }

export function useLocale() { return useContext(I18nContext).locale; }

export function useSetLocale() { return useContext(I18nContext).setLocale; }

export function currentLocale(): Locale { return detectLocale(); }
